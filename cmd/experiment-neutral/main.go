// experiment-neutral replays one pre-generated trace against isolated systems
// in a counterbalanced order.
package main

import (
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"time"

	basynq "github.com/hibiken/asynq"
	"github.com/redis/go-redis/v9"

	"github.com/aminkbi/taskforge/internal/experiment"
	asynqadapter "github.com/aminkbi/taskforge/internal/experiment/adapters/asynq"
	taskforgeadapter "github.com/aminkbi/taskforge/internal/experiment/adapters/taskforge"
)

func main() {
	tracePath := flag.String("trace", "", "immutable trace JSON generated by experiment-trace")
	output := flag.String("output", "artifacts/experiments/open-loop", "new raw-result directory")
	addr := flag.String("redis-addr", env("TASKFORGE_REDIS_ADDR", "localhost:6379"), "Redis address")
	db := flag.Int("redis-db", envInt("TASKFORGE_EXPERIMENT_REDIS_DB", 14), "dedicated non-production Redis DB")
	repetition := flag.Int("repetition", 0, "counterbalance repetition index")
	concurrency := flag.Int("concurrency", 16, "expert-tuned common nominal worker concurrency")
	systems := flag.String("systems", "taskforge-full,taskforge-no-admission,taskforge-no-dependency-budget,asynq", "comma-separated systems to replay")
	admissionPending := flag.Int64("taskforge-admission-pending", 512, "TaskForge admission pending limit")
	snapshot := flag.Duration("snapshot-period", 100*time.Millisecond, "telemetry sampling interval")
	drain := flag.Duration("drain-timeout", 2*time.Minute, "maximum post-arrival drain")
	cpuCost := flag.Float64("cost-cpu-second", 0, "cost-unit rate per Redis CPU second")
	networkCost := flag.Float64("cost-network-gb", 0, "cost-unit rate per Redis network GB")
	memoryCost := flag.Float64("cost-memory-gb-second", 0, "cost-unit rate per Redis memory GB-second")
	flag.Parse()
	if *tracePath == "" {
		fatal("-trace is required; arrivals may not be generated inside the replay command")
	}
	if *repetition < 0 {
		fatal("-repetition must be non-negative")
	}
	if *db < 1 {
		fatal("refusing Redis DB %d; choose a dedicated non-zero DB", *db)
	}
	trace, err := experiment.LoadOpenLoopTrace(*tracePath)
	if err != nil {
		fatal("load trace: %v", err)
	}
	client := redis.NewClient(&redis.Options{Addr: *addr, DB: *db})
	defer client.Close()
	ctx := context.Background()
	if err := client.Ping(ctx).Err(); err != nil {
		fatal("connect Redis: %v", err)
	}
	factories := map[string]func() experiment.OpenLoopAdapter{
		"taskforge-fifo-static": func() experiment.OpenLoopAdapter {
			return taskforgeadapter.New(taskforgeadapter.Config{Name: "taskforge-fifo-static", Client: client, Concurrency: *concurrency, DisableFairness: true, DisableAdaptive: true, DisableDependencyBudget: true})
		},
		"taskforge-full": func() experiment.OpenLoopAdapter {
			return taskforgeadapter.New(taskforgeadapter.Config{Name: "taskforge-full", Client: client, Concurrency: *concurrency, AdmissionMaxPending: *admissionPending, DependencyBudgetCapacity: trace.Profile.Downstream.Capacity})
		},
		"taskforge-no-admission": func() experiment.OpenLoopAdapter {
			return taskforgeadapter.New(taskforgeadapter.Config{Name: "taskforge-no-admission", Client: client, Concurrency: *concurrency, DependencyBudgetCapacity: trace.Profile.Downstream.Capacity})
		},
		"taskforge-no-dependency-budget": func() experiment.OpenLoopAdapter {
			return taskforgeadapter.New(taskforgeadapter.Config{Name: "taskforge-no-dependency-budget", Client: client, Concurrency: *concurrency, AdmissionMaxPending: *admissionPending, DependencyBudgetCapacity: trace.Profile.Downstream.Capacity, DisableDependencyBudget: true})
		},
		"asynq": func() experiment.OpenLoopAdapter {
			return asynqadapter.New(asynqadapter.Config{Redis: basynq.RedisClientOpt{Addr: *addr, DB: *db}, Client: client, Concurrency: *concurrency})
		},
	}
	selected := strings.Split(*systems, ",")
	for index := range selected {
		selected[index] = strings.TrimSpace(selected[index])
		if _, ok := factories[selected[index]]; !ok {
			fatal("unknown system %q", selected[index])
		}
	}
	if len(selected) == 0 || slices.Contains(selected, "") {
		fatal("-systems must name at least one system")
	}
	order := experiment.CounterbalancedOrder(selected, trace.Seed, *repetition)
	for position, name := range order {
		if err := client.FlushDB(ctx).Err(); err != nil {
			fatal("clear dedicated experiment DB: %v", err)
		}
		result, err := experiment.ReplayOpenLoop(ctx, trace, factories[name](), position, experiment.ReplayOptions{
			SnapshotPeriod: *snapshot, DrainTimeout: *drain,
			Cost: experiment.CostModel{CPUSecond: *cpuCost, NetworkGB: *networkCost, MemoryGBSecond: *memoryCost},
		})
		if err != nil {
			fatal("%s: %v", name, err)
		}
		path := filepath.Join(*output, fmt.Sprintf("%s--%s--r%d.json", trace.ID, name, *repetition))
		if err := experiment.WriteOpenLoopResult(path, result); err != nil {
			fatal("write %s result: %v", name, err)
		}
		fmt.Printf("%s (excluded=%t)\n", path, result.Excluded)
	}
}

func env(key, fallback string) string {
	if value := os.Getenv(key); value != "" {
		return value
	}
	return fallback
}

func envInt(key string, fallback int) int {
	if value, err := strconv.Atoi(os.Getenv(key)); err == nil && value > 0 {
		return value
	}
	return fallback
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
