// experiment-neutral replays one pre-generated trace against isolated systems
// in a counterbalanced order.
package main

import (
	"context"
	"flag"
	"fmt"
	"path/filepath"
	"slices"
	"strings"
	"time"

	basynq "github.com/hibiken/asynq"
	"github.com/redis/go-redis/v9"

	"github.com/aminkbi/taskforge/research/internal/expcli"
	"github.com/aminkbi/taskforge/research/internal/experiment"
	asynqadapter "github.com/aminkbi/taskforge/research/internal/experiment/adapters/asynq"
	taskforgeadapter "github.com/aminkbi/taskforge/research/internal/experiment/adapters/taskforge"
)

func main() {
	tracePath := flag.String("trace", "", "immutable trace JSON generated by experiment-trace")
	output := flag.String("output", "artifacts/experiments/open-loop", "new raw-result directory")
	addr := flag.String("redis-addr", expcli.Env("TASKFORGE_REDIS_ADDR", "localhost:6379"), "Redis address")
	network := flag.String("redis-network", expcli.Env("TASKFORGE_REDIS_NETWORK", "tcp"), "Redis network: tcp or unix")
	db := flag.Int("redis-db", expcli.EnvInt("TASKFORGE_EXPERIMENT_REDIS_DB", 14), "dedicated non-production Redis DB")
	repetition := flag.Int("repetition", 0, "counterbalance repetition index")
	concurrency := flag.Int("concurrency", 16, "expert-tuned common nominal worker concurrency")
	systems := flag.String("systems", "taskforge-full,taskforge-no-admission,taskforge-no-dependency-budget,asynq", "comma-separated systems to replay")
	admissionPending := flag.Int64("taskforge-admission-pending", 512, "TaskForge admission pending limit")
	snapshot := flag.Duration("snapshot-period", 100*time.Millisecond, "telemetry sampling interval")
	drain := flag.Duration("drain-timeout", 2*time.Minute, "maximum post-arrival drain")
	cpuCost := flag.Float64("cost-cpu-second", 0, "cost-unit rate per Redis CPU second")
	networkCost := flag.Float64("cost-network-gb", 0, "cost-unit rate per Redis network GB")
	memoryCost := flag.Float64("cost-memory-gb-second", 0, "cost-unit rate per Redis memory GB-second")
	flag.Parse()
	if *tracePath == "" {
		expcli.Fatal("-trace is required; arrivals may not be generated inside the replay command")
	}
	if *repetition < 0 {
		expcli.Fatal("-repetition must be non-negative")
	}
	if *db < 1 {
		expcli.Fatal("refusing Redis DB %d; choose a dedicated non-zero DB", *db)
	}
	if *network != "tcp" && *network != "unix" {
		expcli.Fatal("-redis-network must be tcp or unix")
	}
	trace, err := experiment.LoadOpenLoopTrace(*tracePath)
	if err != nil {
		expcli.Fatal("load trace: %v", err)
	}
	client := redis.NewClient(&redis.Options{Network: *network, Addr: *addr, DB: *db})
	defer client.Close()
	ctx := context.Background()
	if err := client.Ping(ctx).Err(); err != nil {
		expcli.Fatal("connect Redis: %v", err)
	}
	factories := map[string]func() experiment.OpenLoopAdapter{}
	for _, name := range []string{"taskforge-fifo-static", "taskforge-static-capacity", "taskforge-full", "taskforge-no-fairness", "taskforge-no-adaptive", "taskforge-no-admission", "taskforge-no-dependency-budget", "taskforge-fairness-only", "taskforge-admission-only", "taskforge-budget-only", "taskforge-adaptive-only"} {
		factories[name] = func() experiment.OpenLoopAdapter {
			config := controlConfig(name, *concurrency, *admissionPending, trace.Profile.Downstream.Capacity)
			config.Client = client
			return taskforgeadapter.New(config)
		}
	}
	factories["asynq"] = func() experiment.OpenLoopAdapter {
		return asynqadapter.New(asynqadapter.Config{Redis: basynq.RedisClientOpt{Network: *network, Addr: *addr, DB: *db}, Client: client, Concurrency: *concurrency})
	}
	selected := strings.Split(*systems, ",")
	for index := range selected {
		selected[index] = strings.TrimSpace(selected[index])
		if _, ok := factories[selected[index]]; !ok {
			expcli.Fatal("unknown system %q", selected[index])
		}
	}
	if len(selected) == 0 || slices.Contains(selected, "") {
		expcli.Fatal("-systems must name at least one system")
	}
	order := experiment.CounterbalancedOrder(selected, trace.Seed, *repetition)
	for position, name := range order {
		if err := client.FlushDB(ctx).Err(); err != nil {
			expcli.Fatal("clear dedicated experiment DB: %v", err)
		}
		result, err := experiment.ReplayOpenLoop(ctx, trace, factories[name](), position, experiment.ReplayOptions{
			SnapshotPeriod: *snapshot, DrainTimeout: *drain,
			Cost: experiment.CostModel{CPUSecond: *cpuCost, NetworkGB: *networkCost, MemoryGBSecond: *memoryCost},
		})
		if err != nil {
			expcli.Fatal("%s: %v", name, err)
		}
		path := filepath.Join(*output, fmt.Sprintf("%s--%s--r%d.json", trace.ID, name, *repetition))
		if err := experiment.WriteOpenLoopResult(path, result); err != nil {
			expcli.Fatal("write %s result: %v", name, err)
		}
		fmt.Printf("%s (excluded=%t)\n", path, result.Excluded)
	}
}

// controlConfig keeps one-control comparisons identical except for the named
// policy. A capacity-matched static arm tests whether adaptation beats tuning.
func controlConfig(name string, concurrency int, admission int64, capacity int) taskforgeadapter.Config {
	c := taskforgeadapter.Config{Name: name, Concurrency: concurrency, MaxConcurrency: concurrency * 2, DependencyBudgetCapacity: capacity,
		DisableFairness: true, DisableAdaptive: true, DisableDependencyBudget: true}
	switch name {
	case "taskforge-static-capacity":
		c.Concurrency = capacity
	case "taskforge-fairness-only":
		c.DisableFairness = false
	case "taskforge-admission-only":
		c.AdmissionMaxPending = admission
	case "taskforge-budget-only":
		c.DisableDependencyBudget = false
	case "taskforge-adaptive-only":
		c.DisableAdaptive = false
	case "taskforge-full", "taskforge-no-fairness", "taskforge-no-adaptive", "taskforge-no-admission", "taskforge-no-dependency-budget":
		c.DisableFairness = name == "taskforge-no-fairness"
		c.DisableAdaptive = name == "taskforge-no-adaptive"
		c.DisableDependencyBudget = name == "taskforge-no-dependency-budget"
		if name != "taskforge-no-admission" {
			c.AdmissionMaxPending = admission
		}
	}
	return c
}
